def extract_pure_road(addr: str) -> str:
    """從地址中提取純路/街名 (去除巷弄號等)"""
    if not addr:
        return ""
    # 去除縣市、行政區字眼
    addr = re.sub(r'^.*?([縣市])', '', addr)
    addr = re.sub(r'^.*?([區鄉鎮市])', '', addr)
    # 取路、街、大道、段
    m = re.search(r'([^\s,號樓]+?(?:路[一二三四五六七八九十\d]*段?|街|大道[一二三四五六七八九十\d]*段?|段))', addr)
    if m:
        return m.group(1).strip()
    return addr.strip()

def get_road_coord(district: str, road: str) -> Optional[Tuple[float, float]]:
    """查詢路名座標，支援模糊段別匹配"""
    pure = extract_pure_road(road)
    d = (district or "").strip()
    
    # 1. 完全比對
    if (d, pure) in TAICHUNG_ROADS:
        return TAICHUNG_ROADS[(d, pure)]
        
    # 2. 忽略段別比對 (例如中清路二段 -> 中清路)
    base_road = re.sub(r'[一二三四五六七八九十\d]+段$', '', pure)
    if (d, base_road) in TAICHUNG_ROADS:
        return TAICHUNG_ROADS[(d, base_road)]
        
    # 3. 搜尋包含關係
    for (k_dist, k_road), coord in TAICHUNG_ROADS.items():
        if k_dist == d and (k_road in pure or pure in k_road):
            return coord
            
    return None

def is_road_too_far(district: str, road1: str, road2: str, max_meters: float = 800.0) -> bool:
    """
    判斷同行政區的兩條路是否距離太遠 (例如中清路 vs 敦富路)
    若距離 > max_meters (預設 800 公尺)，回傳 True (太遠，非同一物件)
    若無法定位或距離 <= max_meters，回傳 False (不排除)
    """
    if not road1 or not road2:
        return False
    pure1 = extract_pure_road(road1)
    pure2 = extract_pure_road(road2)
    if pure1 == pure2 or pure1 in pure2 or pure2 in pure1:
        return False
        
    c1 = get_road_coord(district, pure1)
    c2 = get_road_coord(district, pure2)
    
    if c1 and c2:
        dist = haversine_distance(c1[0], c1[1], c2[0], c2[1])
        if dist > max_meters:
            return True
            
    return False
